def predict_targets(training, ei, data: dict, prepared: dict, split: dict,
                    intervention: Mapping[str, np.ndarray], *, seed: int, state: str,
                    device: torch.device, batch_size: int) -> np.ndarray:
    path = target_path(len(intervention["atom_scores"]), seed, state)
    if path.exists():
        return np.load(path, allow_pickle=False)["target"].astype(np.float64)
    model, _ = ei.load_model(training, data, prepared["attributes_z"].shape[1], seed, device)
    centers = ei.select_centers(training, data, prepared, split, [state])
    center = {key: value for key, value in centers[0]["batch"].items() if key != "target"}
    samples = len(intervention["atom_scores"])
    outputs: list[np.ndarray] = []
    with torch.inference_mode():
        for start in range(0, samples, batch_size):
            stop = min(samples, start + batch_size)
            width = stop - start
            batch = {
                "recent": torch.from_numpy(intervention["recent"][start:stop]).to(device),
                "daily": torch.from_numpy(intervention["daily"][start:stop]).to(device),
                "weekly": torch.from_numpy(intervention["weekly"][start:stop]).to(device),
            }
            for key, value in center.items():
                if key in batch:
                    continue
                batch[key] = value.unsqueeze(0).expand(width, *value.shape).clone().to(device)
            outputs.append(model(batch).cpu().numpy().reshape(width, -1))
    target = np.concatenate(outputs).astype(np.float64)
    noise_covariance, noise_meta = ei.residual_covariance(training, model, prepared, split, device)
    noise = np.random.default_rng(910_000 + 1000 * seed + DEFAULT_STATES.index(state)).multivariate_normal(
        np.zeros(target.shape[1]), noise_covariance, size=samples
    )
    target += noise
    path.parent.mkdir(parents=True, exist_ok=True)
    stored_target = target.astype(np.float32)
    np.savez_compressed(path, target=stored_target, noise_metadata=np.asarray(json.dumps(noise_meta)))
    return stored_target.astype(np.float64)


class BlockConditionalOracle:
    """Cached affine-TM Xi values for two-dimensional source atoms."""

    def __init__(self, conditional: np.ndarray, atom_count: int, components: int):
        self.conditional = np.asarray(conditional, dtype=np.float64)
        self.atom_count = int(atom_count)
        self.components = int(components)
        self._ei_cache: dict[tuple[int, ...], float] = {}
        self._xi_cache: dict[tuple[int, ...], float] = {
            (index,): 0.0 for index in range(atom_count)
        }
        self.singletons = np.asarray([self.ei((index,)) for index in range(atom_count)])
        self.evaluations = atom_count
        self.last_progress = time.monotonic()

    def dimensions(self, indices: Iterable[int]) -> np.ndarray:
        return np.asarray(
            [dimension for atom in sorted(int(value) for value in indices)
             for dimension in range(atom * self.components, (atom + 1) * self.components)],
            dtype=int,
        )

    def ei(self, indices: Iterable[int]) -> float:
        key = tuple(sorted(int(value) for value in indices))
        if not key:
            return 0.0
        cached = self._ei_cache.get(key)
        if cached is not None:
            return cached
        dimensions = self.dimensions(key)
        factor = cholesky(self.conditional[np.ix_(dimensions, dimensions)], lower=True, check_finite=False)
        logdet = 2.0 * np.log(np.diag(factor)).sum()
        value = float(-0.5 * logdet / LOG2)
        self._ei_cache[key] = value
        return value

    def xi(self, indices: Iterable[int]) -> float:
        key = tuple(sorted(int(value) for value in indices))
        if not key:
            return 0.0
        cached = self._xi_cache.get(key)
        if cached is not None:
            return cached
        value = float(self.ei(key) - self.singletons[list(key)].sum())
        self._xi_cache[key] = value
        self.evaluations += 1
        if ACTIVE_PROGRESS is not None and time.monotonic() - self.last_progress > 5:
            ACTIVE_PROGRESS.write("affine_search", metrics={"coalitions": self.evaluations}, force=True)
            self.last_progress = time.monotonic()
        return value


def fit_affine_oracle(atom_scores: np.ndarray, target: np.ndarray, fit_indices: np.ndarray,
                      *, target_ridge: float
                      ) -> tuple[BlockConditionalOracle, dict[str, float], np.ndarray]:
    x = atom_scores[fit_indices].reshape(len(fit_indices), -1).astype(np.float64)
    y = target[fit_indices].astype(np.float64)
    y_mean = y.mean(axis=0)
    y_scale = y.std(axis=0, ddof=1)
    if np.any(y_scale < 1.0e-8):
        raise RuntimeError("Degenerate MGSTN target dimension")
    y = (y - y_mean) / y_scale
    x = x - x.mean(axis=0)
    if len(x) <= x.shape[1]:
        raise ValueError("Affine regression requires more fit samples than source dimensions")
    cross, _, rank, _ = np.linalg.lstsq(x, y, rcond=None)
    if rank != x.shape[1]:
        raise RuntimeError(f"Rank-deficient affine source design: {rank}/{x.shape[1]}")
    residual = y - x @ cross
    residual_covariance = residual.T @ residual / (len(x) - 1)
    residual_covariance += float(target_ridge) * np.eye(y.shape[1])
    # Coherent Gaussian affine-TM readout: X~N(0,I), Y=X B+epsilon.
    # Do not combine the identity source prior with an unrelated empirical Y covariance.
    target_covariance = cross.T @ cross + residual_covariance
    explained = cross @ np.linalg.solve(target_covariance, cross.T)
    conditional = np.eye(x.shape[1]) - explained
    conditional = 0.5 * (conditional + conditional.T)
    eigenvalues = np.linalg.eigvalsh(conditional)
    audit = {
        "conditional_min_eigenvalue": float(eigenvalues.min()),
        "conditional_max_eigenvalue": float(eigenvalues.max()),
        "target_condition_number": float(np.linalg.cond(target_covariance)),
        "design_rank": int(rank),
        "training_variance_explained": float(1 - np.sum(residual**2) / np.sum(y**2)),
        "residual_min_eigenvalue": float(np.linalg.eigvalsh(residual_covariance).min()),
    }
    if eigenvalues.min() <= 0.0:
        raise RuntimeError(
            f"Affine conditional covariance is not positive definite: min={eigenvalues.min():.6g}"
        )
    return BlockConditionalOracle(conditional, atom_scores.shape[1], atom_scores.shape[2]), audit, cross


def pair_affinity(oracle: BlockConditionalOracle, atom_count: int) -> tuple[np.ndarray, int, float]:
    affinity = np.zeros((atom_count, atom_count), dtype=np.float64)
    tolerance_zero = 0
    minimum = math.inf
    for left in range(atom_count):
        for right in range(left + 1, atom_count):
            value = oracle.xi((left, right))
            minimum = min(minimum, value)
            if value < -AFFINE_TOLERANCE_BITS:
                raise RuntimeError(
                    f"Pair Syn nonnegativity violation: {value:.12g} bits; "
                    f"threshold={-AFFINE_TOLERANCE_BITS}; affected_count=1"
                )
            if value < 0.0:
                tolerance_zero += 1
                value = 0.0
            affinity[left, right] = affinity[right, left] = value
    return affinity, tolerance_zero, float(minimum)


def audit_nonnegative(values, tolerance: float, context: str) -> dict:
    values = np.asarray(values, dtype=float)
    if not np.all(np.isfinite(values)):
        raise RuntimeError(f"{context}: nonfinite Syn")
    minimum = float(values.min())
    affected = int(np.sum(values < -tolerance))
    if affected:
        raise RuntimeError(f"{context}: Syn nonnegativity violation; minimum={minimum:.12g} bits; "
                           f"threshold={-tolerance}; affected_count={affected}")
    return {"minimum_bits": minimum, "tolerance_zero_count": int(np.sum(values < 0)),
            "violation_count": affected, "tolerance_bits": tolerance}


def build_time_prior_tree(oracle: BlockConditionalOracle, affinity: np.ndarray, *, exact_max_size: int,
                          audit: dict[str, int]) -> ScalableHierarchyNode:
    """Build an SPT constrained to intact time blocks at the first two levels.

    The root optimizer compares the three legal time-block bipartitions. It does
    not prescribe which scale is isolated. The selected two-scale block is then
    refined into its two intact scales, after which each scale receives an
    independently searched spatial SPT.
    """
    groups = {
        name: tuple(zone * 3 + TIME_NAMES.index(name) for zone in range(oracle.atom_count // 3))
        for name in TIME_NAMES
    }
    all_indices = tuple(range(oracle.atom_count))
    all_xi = oracle.xi(all_indices)
    candidates = []
    for isolated_name in TIME_NAMES:
        paired_names = tuple(name for name in TIME_NAMES if name != isolated_name)
        paired_indices = tuple(sorted(groups[paired_names[0]] + groups[paired_names[1]]))
        captured = oracle.xi(groups[isolated_name]) + oracle.xi(paired_indices)
        residual = float(all_xi - captured)
        nonnegative = audit_nonnegative(
            [residual], AFFINE_TOLERANCE_BITS, f"time-block root {isolated_name} | {paired_names}"
        )
        audit["candidate_count"] += 1
        audit["tolerance_zero_count"] += nonnegative["tolerance_zero_count"]
        candidates.append((captured, -residual, isolated_name, paired_names, paired_indices, residual))
    _, _, isolated_name, paired_names, paired_indices, root_syn = max(
        candidates, key=lambda row: (row[0], row[1], row[2])
    )

    subtree_depth = {name: (1 if name == isolated_name else 2) for name in TIME_NAMES}
    subtrees = {
        name: build_scalable_hierarchy(
            groups[name], oracle, affinity, exact_max_size=exact_max_size,
            tolerance=AFFINE_TOLERANCE_BITS, depth=subtree_depth[name], audit=audit,
        ) for name in TIME_NAMES
    }
    macro_syn = float(
        oracle.xi(paired_indices)
        - oracle.xi(groups[paired_names[0]])
        - oracle.xi(groups[paired_names[1]])
    )
    macro_audit = audit_nonnegative(
        [macro_syn], AFFINE_TOLERANCE_BITS, f"time-block refinement {paired_names}"
    )
    audit["tolerance_zero_count"] += macro_audit["tolerance_zero_count"]
    macro = ScalableHierarchyNode(
        paired_indices, oracle.xi(paired_indices), macro_syn, 1, "time-block-refinement",
        tuple(subtrees[name] for name in paired_names),
    )
    return ScalableHierarchyNode(
        all_indices, all_xi, root_syn, 0, "time-block-search",
        (subtrees[isolated_name], macro),
    )


def tree_metrics(root: ScalableHierarchyNode) -> dict[str, float | int]:
    nodes = flatten_nodes(root)
    internal = [node for node in nodes if node.children]
    leaves = [node for node in nodes if not node.children]
    depths = [node.depth for node in leaves]

    def spine_length(node: ScalableHierarchyNode) -> int:
        count = 0
        current = node
        while current.children:
            count += 1
            current = max(current.children, key=lambda child: (child.size, -min(child.indices)))
        return count

    purity = []
    for node in internal:
        counts = np.bincount([index % 3 for index in node.indices], minlength=3)
        purity.append(float(counts.max() / node.size))
    raw_syn = np.asarray([node.syn_bits for node in internal])
    audit_nonnegative(raw_syn, AFFINE_TOLERANCE_BITS, "tree metric weights")
    weights = np.where(raw_syn < 0, 0., raw_syn)
    return {
        "internal_node_count": len(internal),
        "maximum_depth": int(max(depths)),
        "mean_leaf_depth": float(np.mean(depths)),
        "dominant_spine_split_count": spine_length(root),
        "dominant_spine_fraction": float(spine_length(root) / max(1, len(internal))),
        "mean_internal_time_purity": float(np.mean(purity)),
        "syn_weighted_time_purity": float(
            np.average(purity, weights=weights) if weights.sum() else np.mean(purity)
        ),
        "same_zone_recent_weekly_pair_count": sum(
            n.size == 2 and n.indices[0] // 3 == n.indices[1] // 3
            and {i % 3 for i in n.indices} == {0, 2} for n in internal),
        "pair_syn_fraction": float(sum(n.syn_bits for n in internal if n.size == 2) / root.xi_bits),
        "top_time_partition_syn_fraction": float(sum(
            n.syn_bits for n in internal if n.search_kind in {"time-block-search", "time-block-refinement"}
        ) / root.xi_bits),
    }


def serialize_tree(node: ScalableHierarchyNode, zone_ids: np.ndarray) -> dict[str, object]:
    counts = {name: int(sum(index % 3 == position for index in node.indices))
              for position, name in enumerate(TIME_NAMES)}
    members = [
        {"atom": int(index), "zone_id": int(zone_ids[index // 3]), "time": TIME_NAMES[index % 3]}
        for index in node.indices
    ]
    return {
        "indices": list(node.indices), "size": node.size, "xi_bits": float(node.xi_bits),
        "syn_bits": float(node.syn_bits), "depth": int(node.depth),
        "search_kind": node.search_kind, "time_counts": counts, "members": members,
        "children": [serialize_tree(child, zone_ids) for child in node.children],
    }


def time_block_split_metadata(root: ScalableHierarchyNode) -> dict[str, object]:
    if root.search_kind != "time-block-search" or len(root.children) != 2:
        raise ValueError("Expected a time-block-search root")
    isolated, paired = root.children
    isolated_scales = sorted({TIME_NAMES[index % 3] for index in isolated.indices})
    paired_scales = sorted({TIME_NAMES[index % 3] for index in paired.indices})
    if len(isolated_scales) != 1 or len(paired_scales) != 2:
        raise RuntimeError("Time-block SPT violated the intact-scale constraint")
    return {
        "selected_root_split": [isolated_scales, paired_scales],
        "root_syn_bits": float(root.syn_bits),
        "paired_block_refinement_syn_bits": float(paired.syn_bits),
        "selection_rule": "maximize child Xi sum among the three intact time-block bipartitions",
    }


def deserialize_tree(payload: Mapping[str, object]) -> ScalableHierarchyNode:
    return ScalableHierarchyNode(
        tuple(int(value) for value in payload["indices"]), float(payload["xi_bits"]),
        float(payload["syn_bits"]), int(payload["depth"]), str(payload["search_kind"]),
        tuple(deserialize_tree(child) for child in payload.get("children", [])),
    )


def closure_error(root: ScalableHierarchyNode) -> float:
    return float(root.xi_bits - sum(node.syn_bits for node in flatten_nodes(root) if node.children))


