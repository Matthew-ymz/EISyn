def child_crosscov_scores(atom_scores: np.ndarray, target: np.ndarray, fit_indices: np.ndarray,
                           coalition: Sequence[int], components: int = 2) -> np.ndarray:
    dimensions = [dimension for atom in coalition for dimension in (atom * 2, atom * 2 + 1)]
    x = atom_scores.reshape(len(atom_scores), -1)[:, dimensions].astype(np.float64)
    y = target.astype(np.float64)
    xf = x[fit_indices] - x[fit_indices].mean(axis=0)
    yf = y[fit_indices] - y[fit_indices].mean(axis=0)
    cross = xf.T @ yf / (len(fit_indices) - 1)
    u, _, _ = np.linalg.svd(cross, full_matrices=False)
    width = min(components, u.shape[1])
    projected = (x - x[fit_indices].mean(axis=0)) @ u[:, :width]
    if width < components:
        projected = np.column_stack([projected, np.zeros((len(x), components - width))])
    mean = projected[fit_indices].mean(axis=0)
    scale = projected[fit_indices].std(axis=0, ddof=1)
    scale[scale < 1.0e-8] = 1.0
    return ((projected - mean) / scale).astype(np.float64)


def selected_splits(root: ScalableHierarchyNode) -> list[tuple[tuple[int, ...], tuple[int, ...], float, int]]:
    rows = []
    for node in flatten_nodes(root):
        if not node.children:
            continue
        rows.append((node.children[0].indices, node.children[1].indices, float(node.syn_bits), node.size))
    return rows


def polynomial_conditional_log_prob(prefix, right, fit, evaluate, *, ridge: float, degree: int = 2):
    """Exact conditional factors of the existing polynomial triangular TM.

    Only right-hand factors enter CMI. Unused prefix densities cancel, so we avoid
    fitting them. Explicit quadratic products replace the generic exponent tensor.
    Ordering, sample SD, residual floor and intercept-unpenalized ridge are unchanged.
    """
    output = np.zeros(len(evaluate), dtype=float)
    for dimension in range(right.shape[1]):
        predictors = np.column_stack([prefix, right[:, :dimension]])
        mean = predictors[fit].mean(axis=0)
        scale = predictors[fit].std(axis=0, ddof=1)
        scale = np.where(scale > 1e-8, scale, 1.0)
        z = (predictors - mean) / scale
        columns = [np.ones(len(z))] + [z[:, j] for j in range(z.shape[1])]
        if degree == 2:
            columns += [z[:, j] * z[:, k] for j, k in combinations_with_replacement(range(z.shape[1]), 2)]
        design = np.column_stack(columns)
        training = design[fit]
        gram = training.T @ training + ridge * np.eye(training.shape[1])
        gram[0, 0] -= ridge
        coefficients = np.linalg.solve(gram, training.T @ right[fit, dimension])
        residual_scale = max(float((right[fit, dimension] - training @ coefficients).std(ddof=1)), 1e-8)
        standardized = (right[evaluate, dimension] - design[evaluate] @ coefficients) / residual_scale
        output += -.5 * (np.log(2*np.pi) + standardized**2) - np.log(residual_scale)
    return output


class FastQuadraticTM:
    @staticmethod
    def estimate_quadratic_cmi(left, right, target, fit_indices, evaluate_indices, *, ridge):
        full = polynomial_conditional_log_prob(np.column_stack([target, left]), right,
                                               fit_indices, evaluate_indices, ridge=ridge)
        reduced = polynomial_conditional_log_prob(target, right, fit_indices, evaluate_indices, ridge=ridge)
        pointwise = (full - reduced) / LOG2
        return {"syn_bits_raw": float(pointwise.mean()),
                "syn_bits_se": float(pointwise.std(ddof=1) / np.sqrt(len(pointwise))),
                "evaluation_samples": int(len(pointwise))}


def quadratic_split_jobs(summary: dict, *, seed: int, state: str, tree_names: Sequence[str]) -> list[dict]:
    cache = np.load(condition_dir(seed, state) / "affine_cache.npz")
    oracle = BlockConditionalOracle(cache["conditional"], summary["source_atoms"], 2)
    jobs = []
    for tree_name in tree_names:
        root = deserialize_tree(summary[tree_name]["tree"])
        nodes = [node for node in flatten_nodes(root) if node.children]
        # Prespecified budget: two runner-ups at the eight strongest non-fixed nodes.
        ranked = sorted([node for node in nodes if not node.search_kind.startswith("time-block") and node.size > 2],
                        key=lambda node: node.syn_bits, reverse=True)[:8]
        for node_index, node in enumerate(nodes):
            left, right = (child.indices for child in node.children)
            jobs.append(dict(tree=tree_name, node_index=node_index, node_size=node.size,
                             left=list(left), right=list(right), affine_syn_bits=node.syn_bits,
                             role="selected"))
            if node.search_kind == "time-block-search":
                groups = {name: tuple(index for index in node.indices if index % 3 == position)
                          for position, name in enumerate(TIME_NAMES)}
                selected = {tuple(left), tuple(right)}
                alternatives = []
                for isolated_name in TIME_NAMES:
                    a = groups[isolated_name]
                    b = tuple(sorted(index for name in TIME_NAMES if name != isolated_name for index in groups[name]))
                    if {a, b} == selected:
                        continue
                    value = oracle.xi(node.indices) - oracle.xi(a) - oracle.xi(b)
                    audit_nonnegative([value], AFFINE_TOLERANCE_BITS, "time-block runner-up split")
                    alternatives.append((value, a, b))
                for rank, (value, a, b) in enumerate(sorted(alternatives), 1):
                    jobs.append(dict(tree=tree_name, node_index=node_index, node_size=node.size,
                                     left=list(a), right=list(b), affine_syn_bits=value,
                                     role=f"time_block_runner_up_{rank}"))
                continue
            if node.search_kind == "time-block-refinement":
                continue
            if node not in ranked:
                continue
            candidates = (_exact_candidates(node.indices) if node.size <= summary.get("exact_max_size", 8) else
                          _scalable_candidates(node.indices, cache["affinity"]))
            alternatives = []
            for a, b in candidates:
                if {a, b} == {left, right}:
                    continue
                value = oracle.xi(node.indices) - oracle.xi(a) - oracle.xi(b)
                audit_nonnegative([value], AFFINE_TOLERANCE_BITS, "runner-up split")
                alternatives.append((value, a, b))
            for rank, (value, a, b) in enumerate(sorted(alternatives)[:2], 1):
                jobs.append(dict(tree=tree_name, node_index=node_index, node_size=node.size,
                                 left=list(a), right=list(b), affine_syn_bits=value,
                                 role=f"runner_up_{rank}"))
    return jobs


def validate_quadratic_condition(intervention: Mapping[str, np.ndarray], target: np.ndarray, summary: dict,
                                 quadratic, *, seed: int, state: str, ridge: float,
                                 tree_names: Sequence[str]) -> dict[str, object]:
    out = condition_dir(seed, state) / f"quadratic_validation_r{ridge:g}.json"
    if out.exists():
        cached = json.loads(out.read_text(encoding="utf-8"))
        if cached["status"] == "passed":
            return cached
        raise RuntimeError(f"Quadratic audit previously failed; inspect {out}")
    fit = intervention["fit_indices"].astype(int)
    evaluate = intervention["evaluate_indices"].astype(int)
    score_cache: dict[tuple[int, ...], np.ndarray] = {}

    def scores(indices: tuple[int, ...]) -> np.ndarray:
        key = tuple(sorted(indices))
        if key not in score_cache:
            score_cache[key] = child_crosscov_scores(
                intervention["atom_scores"], target, fit, key, components=2
            )
        return score_cache[key]

    records = []
    jobs = quadratic_split_jobs(summary, seed=seed, state=state, tree_names=tree_names)
    started = time.monotonic()
    payload = {
        "seed": seed, "state": state, "ridge": ridge,
        "status": "running", "planned_records": len(jobs),
        "estimator": "degree-2 TM after train-fit two-crosscov-direction projection of hurdle PCs",
        "target_semantics": "66 target-wise projected CMI diagnostics; not full-coalition or joint-target Syn",
        "nonnegative_tolerance_bits": QUADRATIC_TOLERANCE_BITS,
        "records": records,
    }
    for number, job in enumerate(tqdm(jobs, desc=f"Projected TM seed={seed} {state}", unit="split")):
        left, right = tuple(job["left"]), tuple(job["right"])
        key = hashlib.sha256(json.dumps([left, right, ridge, summary["input_sha256"], "projection_v2"]).encode()).hexdigest()[:24]
        split_path = out.parent / "quadratic_splits" / f"{key}.json"
        if split_path.exists():
            estimates = json.loads(split_path.read_text())
        else:
            left_scores, right_scores = scores(left), scores(right)
            estimates = {"zone_values_bits": [], "zone_standard_errors_bits": []}
            for zone in range(target.shape[1] // 2):
                result = quadratic.estimate_quadratic_cmi(
                    left_scores, right_scores, target[:, 2 * zone:2 * zone + 2], fit, evaluate, ridge=ridge)
                estimates["zone_values_bits"].append(float(result["syn_bits_raw"]))
                estimates["zone_standard_errors_bits"].append(float(result["syn_bits_se"]))
            atomic_json(split_path, estimates)
        values = np.asarray(estimates["zone_values_bits"])
        records.append(job | estimates | {
            "quadratic_targetwise_sum_bits": float(values.sum()),
            "quadratic_min_zone_bits": float(values.min()),
            "quadratic_negative_zone_count": int(np.sum(values < 0)),
            "quadratic_violation_zone_count": int(np.sum(values < -QUADRATIC_TOLERANCE_BITS)),
        })
        payload["minimum_zone_syn_bits"] = min(row["quadratic_min_zone_bits"] for row in records)
        payload["node_with_any_violation_count"] = sum(row["quadratic_violation_zone_count"] > 0 for row in records)
        payload["elapsed_seconds"] = time.monotonic() - started
        try:
            audit_nonnegative(values, QUADRATIC_TOLERANCE_BITS, f"projected quadratic {seed}/{state}/{number}")
        except RuntimeError as error:
            payload.update(status="failed", error=str(error))
            atomic_json(out, payload)
            raise
        if ACTIVE_PROGRESS is not None:
            ACTIVE_PROGRESS.write("quadratic_diagnostic", metrics={"seed": seed, "state": state,
                                  "completed_splits": number + 1, "total_splits": len(jobs),
                                  "phase_eta_seconds": payload["elapsed_seconds"] / (number + 1) * (len(jobs)-number-1)})
    payload["status"] = "passed"
    atomic_json(out, payload)
    return payload


def leaf_order(root: ScalableHierarchyNode) -> list[int]:
    if not root.children:
        return [root.indices[0]]
    return [index for child in root.children for index in leaf_order(child)]


def tree_positions(root: ScalableHierarchyNode) -> dict[tuple[int, ...], tuple[float, float]]:
    order = leaf_order(root)
    leaf_x = {atom: float(position) for position, atom in enumerate(order)}
    positions: dict[tuple[int, ...], tuple[float, float]] = {}

    def visit(node: ScalableHierarchyNode) -> tuple[float, float]:
        if not node.children:
            point = (leaf_x[node.indices[0]], 0.0)
        else:
            child_points = [visit(child) for child in node.children]
            x = sum(point[0] * child.size for point, child in zip(child_points, node.children, strict=True)) / node.size
            point = (x, math.log2(node.size) / math.log2(root.size))
        positions[node.indices] = point
        return point

    visit(root)
    return positions


def plot_tree(axis, root: ScalableHierarchyNode, *, label: str, zone_ids: np.ndarray,
              norm: Normalize) -> None:
    positions = tree_positions(root)
    internal = [node for node in flatten_nodes(root) if node.children]
    audit_nonnegative([node.syn_bits for node in internal], AFFINE_TOLERANCE_BITS, "figure")
    cmap = mpl.colormaps["YlGnBu"]
    for node in internal:
        parent = positions[node.indices]
        children = [positions[child.indices] for child in node.children]
        axis.plot([children[0][0], children[1][0]], [parent[1], parent[1]], color="#B7C0C8", lw=0.45, zorder=1)
        for child in children:
            axis.plot([child[0], child[0]], [child[1], parent[1]], color="#B7C0C8", lw=0.45, zorder=1)
        # Audit above rejects significant negatives; only tolerance-scale negatives
        # are displayed at zero. Cached raw Syn values are never changed.
        display_syn = 0.0 if node.syn_bits < 0 else node.syn_bits
        axis.scatter([parent[0]], [parent[1]], s=5 + 24 * norm(display_syn),
                     c=[cmap(norm(display_syn))], edgecolors="#35515D", lw=0.3, zorder=3)
    order = leaf_order(root)
    for position, atom in enumerate(order):
        axis.scatter([position], [0], s=8, color=TIME_COLORS[TIME_NAMES[atom % 3]],
                     edgecolors="white", lw=0.25, zorder=4)
    if root.search_kind == "time-block-search":
        for node in internal:
            if node.size == 66 and len({i % 3 for i in node.indices}) == 1:
                x, y = positions[node.indices]
                time_name = TIME_NAMES[node.indices[0] % 3]
                axis.text(x, y + .025, f"{time_name} (66 zones)", ha="center", va="bottom",
                          fontsize=8, color=TIME_COLORS[time_name])
    axis.text(0.0, 1.02, label, transform=axis.transAxes, ha="left", va="bottom", fontsize=8.0, color="#24313C")
    axis.set_xlim(-2, root.size + 1)
    axis.set_ylim(-0.015, 1.04)
    axis.set_xticks(range(len(order)), [f"{zone_ids[i//3]} {'RDW'[i%3]}" for i in order], rotation=90, fontsize=5)
    axis.tick_params(axis="x", length=0, pad=3)
    axis.set_xlabel("Source atoms: Taxi Zone ID × time scale (R: recent; D: daily; W: weekly)", labelpad=8)
    axis.set_ylabel("Coalition size (log scale)")
    ticks = [1, 2, 4, 8, 16, 32, 66, 132, 198]
    axis.set_yticks(np.log2(ticks) / np.log2(root.size), [str(t) for t in ticks])
    axis.spines[["top", "right", "bottom"]].set_visible(False)


def representative_condition(summaries: Sequence[dict]) -> tuple[int, str]:
    values = np.asarray([row["unconstrained"]["tree"]["xi_bits"] for row in summaries], dtype=float)
    index = int(np.argmin(np.abs(values - values.mean())))
    return int(summaries[index]["seed"]), str(summaries[index]["state"])


