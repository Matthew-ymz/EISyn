def run_affine_condition(intervention: Mapping[str, np.ndarray], target: np.ndarray, *, seed: int,
                         state: str, target_ridge: float,
                         exact_max_size: int) -> dict[str, object]:
    out = condition_dir(seed, state)
    summary_path = out / "affine_summary.json"
    signature = hashlib.sha256(intervention["atom_scores"].tobytes() + target.tobytes()).hexdigest()
    if summary_path.exists():
        cached = json.loads(summary_path.read_text(encoding="utf-8"))
        if signature not in (cached.get("input_sha256"), cached.get("verified_roundtrip_input_sha256")):
            raise RuntimeError("Cached affine inputs differ from this run")
        for name in ("unconstrained", "time_prior"):
            cached[name]["tree_metrics"] = tree_metrics(deserialize_tree(cached[name]["tree"]))
        return cached
    started = time.monotonic()
    oracle, covariance_audit, cross = fit_affine_oracle(
        intervention["atom_scores"], target, intervention["fit_indices"].astype(int),
        target_ridge=target_ridge,
    )
    affinity, pair_zero, pair_minimum = pair_affinity(oracle, oracle.atom_count)
    mixed_audit = {"candidate_count": 0, "tolerance_zero_count": 0}
    mixed = build_scalable_hierarchy(
        tuple(range(oracle.atom_count)), oracle, affinity, exact_max_size=exact_max_size,
        tolerance=AFFINE_TOLERANCE_BITS, audit=mixed_audit,
    )
    prior_audit = {"candidate_count": 0, "tolerance_zero_count": 0}
