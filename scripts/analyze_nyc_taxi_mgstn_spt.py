def aggregate_summary(summaries: Sequence[dict], validations: Sequence[dict], figures: Sequence[Path]) -> dict:
    if any(payload.get("status") != "passed" for payload in validations):
        raise RuntimeError("Cannot aggregate failed or incomplete quadratic audits")
    rows = {}
    for tree_name in ("unconstrained", "time_prior"):
        metrics = [tree_metrics(deserialize_tree(summary[tree_name]["tree"])) for summary in summaries]
        rows[tree_name] = {
            key: {
                "mean": float(np.mean([row[key] for row in metrics])),
                "sd": float(np.std([row[key] for row in metrics], ddof=1)) if len(metrics) > 1 else 0.,
                "minimum": float(min(row[key] for row in metrics)),
                "maximum": float(max(row[key] for row in metrics)),
            }
            for key in metrics[0]
        }
    validation_records = [record for payload in validations for record in payload["records"]]
    return {
        "status": "complete_affine_and_projected_diagnostics" if validations else "complete_affine_only",
        "conditions": len(summaries),
        "comparison": "only the allowed SPT partition structure changes",
        "affine_search": rows,
        "joint_target_xi_bits": [summary["unconstrained"]["tree"]["xi_bits"] for summary in summaries],
        "affine_search_seconds": [summary["elapsed_seconds"] for summary in summaries],
        "maximum_absolute_closure_error_bits": max(abs(summary[name]["closure_error_bits"])
            for summary in summaries for name in ("unconstrained", "time_prior")),
        "representative_condition": representative_condition(summaries),
        "quadratic_validation": {
            "record_count": len(validation_records),
            "minimum_zone_syn_bits": float(min(record["quadratic_min_zone_bits"] for record in validation_records)) if validation_records else None,
            "node_with_any_violation_count": int(sum(record["quadratic_violation_zone_count"] > 0 for record in validation_records)),
            "tolerance_negative_count": sum(record["quadratic_negative_zone_count"] for record in validation_records),
            "targetwise_estimate_count_including_reused_splits": sum(len(record["zone_values_bits"]) for record in validation_records),
            "interpretation": "Projected target-wise CMI checks only; not full joint-target tree validation or an independent confirmation set",
            "tolerance_bits": QUADRATIC_TOLERANCE_BITS,
        },
        "figures": [str(path.relative_to(ROOT)) for path in figures],
    }


