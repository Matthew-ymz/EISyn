def prepare_shared_intervention(training, data: dict, prepared: dict, split: dict,
                                *, samples: int, components: int, smoke: bool) -> dict[str, np.ndarray]:
    path = intervention_path(samples, components)
    if path.exists():
        saved = np.load(path, allow_pickle=False)
        return {key: saved[key] for key in saved.files}

    train_times = np.asarray(split["indices"]["train"], dtype=int)
    pools_z = history_pools(prepared["flow_z"], train_times)
    pools_raw = history_pools(data["flow"], train_times)
    zone_count = int(data["zone_ids"].shape[0])
    rng = np.random.default_rng(20260831)
    indices = {
        name: rng.integers(0, len(train_times), size=(samples, zone_count), dtype=np.int32)
        for name in TIME_NAMES
    }
    order = rng.permutation(samples)
    fit_n = int(round(0.70 * samples))
    fit_indices = np.sort(order[:fit_n]).astype(np.int32)
    evaluate_indices = np.sort(order[fit_n:]).astype(np.int32)
    histories: dict[str, np.ndarray] = {}
    atom_scores = np.empty((samples, zone_count * len(TIME_NAMES), components), dtype=np.float32)
    atom_explained = np.empty((zone_count * len(TIME_NAMES), components), dtype=np.float32)

    for time_index, name in enumerate(TIME_NAMES):
        width = pools_z[name].shape[-1]
        values_z = np.empty((samples, zone_count, 2, width), dtype=np.float32)
        for zone in range(zone_count):
            selected = indices[name][:, zone]
            values_z[:, zone] = pools_z[name][selected, zone]
            raw = pools_raw[name][selected, zone].reshape(samples, -1)
            features = hurdle_features(raw)
            pca = PCA(n_components=components, svd_solver="full")
            pca.fit(features[fit_indices])
            score = pca.transform(features).astype(np.float64)
            mean = score[fit_indices].mean(axis=0)
            scale = score[fit_indices].std(axis=0, ddof=1)
            if np.any(scale < 1.0e-8):
                raise RuntimeError(f"Degenerate hurdle PC for {name}, zone {zone}")
            score = (score - mean) / scale
            atom = zone * len(TIME_NAMES) + time_index
            atom_scores[:, atom] = score.astype(np.float32)
            atom_explained[atom] = pca.explained_variance_ratio_.astype(np.float32)
        histories[name] = values_z

    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        path,
        recent=histories["recent"],
        daily=histories["daily"],
        weekly=histories["weekly"],
        atom_scores=atom_scores,
        atom_explained=atom_explained,
        fit_indices=fit_indices,
        evaluate_indices=evaluate_indices,
        recent_indices=indices["recent"],
        daily_indices=indices["daily"],
        weekly_indices=indices["weekly"],
        zone_ids=data["zone_ids"].astype(np.int32),
        zone_names=data["zone_names"].astype(str),
    )
    return {
        "recent": histories["recent"], "daily": histories["daily"],
        "weekly": histories["weekly"], "atom_scores": atom_scores,
        "atom_explained": atom_explained, "fit_indices": fit_indices,
        "evaluate_indices": evaluate_indices, "zone_ids": data["zone_ids"].astype(np.int32),
        "zone_names": data["zone_names"].astype(str),
    }


